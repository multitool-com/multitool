const MESES = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

/** "2026-10-15" → "15 Oct 2026" (determinístico: igual no servidor e no cliente). */
export function formatReviewedDate(iso: string): string {
  const [year, month, day] = iso.split("-");
  const index = Number(month) - 1;
  if (!year || Number.isNaN(index) || !MESES[index]) return iso;
  return `${Number(day)} ${MESES[index]} ${year}`;
}
